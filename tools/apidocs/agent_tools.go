package main

import (
	"fmt"
	"go/format"
	"os"
	"strings"

	"github.com/open-mrp/api/services/api-gateway/pkg/authz"
	"github.com/open-mrp/apikit/openapi"
)

// agentToolsGoPath is the generated Go catalog, relative to the project root the tool chdirs into. Endpoint-tools live entirely in code — there is intentionally no DB seed, so adding endpoints never needs a migration.
const agentToolsGoPath = "services/agent-service/internal/agents/endpoint_tools_gen.go"

// generateAgentTools writes the agent-service catalog of every endpoint flagged AgentTool, with the permissions and role type each tool's access policy requires.
func generateAgentTools(cfg openapi.Config) error {
	tools, err := openapi.AgentTools(cfg)
	if err != nil {
		return err
	}
	if err := writeAgentToolsGo(tools); err != nil {
		return err
	}
	logInfof("Wrote %d endpoint agent tools to %s", len(tools), agentToolsGoPath)
	return nil
}

func writeAgentToolsGo(tools []openapi.AgentTool) error {
	var b strings.Builder
	b.WriteString("// Code generated by tools/apidocs --agent-tools. DO NOT EDIT.\n\n")
	b.WriteString("package agents\n\n")
	b.WriteString("// EndpointTools is the generated catalog of api-gateway endpoints exposed as agent tools (endpoints flagged AgentTool=true). Regenerate with `make generate` or `make gen-agent-tools`.\n")
	b.WriteString("var EndpointTools = []EndpointToolDescriptor{\n")
	for _, t := range tools {
		b.WriteString("\t{\n")
		fmt.Fprintf(&b, "\t\tSlug:          %q,\n", t.Slug)
		fmt.Fprintf(&b, "\t\tDisplayName:   %q,\n", t.DisplayName)
		fmt.Fprintf(&b, "\t\tDescription:   %q,\n", t.Description)
		fmt.Fprintf(&b, "\t\tMethod:        %q,\n", t.Method)
		fmt.Fprintf(&b, "\t\tRouteTemplate: %q,\n", t.RouteTemplate)
		fmt.Fprintf(&b, "\t\tInputSchema:   %q,\n", string(t.InputSchema))
		fmt.Fprintf(&b, "\t\tGroup:         %q,\n", t.Group)
		if t.ReadOnly {
			b.WriteString("\t\tReadOnly:      true,\n")
		}
		if p, ok := authz.Of(t.Auth); ok {
			if p.RoleType != "" {
				fmt.Fprintf(&b, "\t\tRequiredRoleType: %q,\n", p.RoleType)
			}
			if perms := policyPermissions(p); len(perms) > 0 {
				quoted := make([]string, len(perms))
				for i, perm := range perms {
					quoted[i] = fmt.Sprintf("%q", perm)
				}
				fmt.Fprintf(&b, "\t\tRequiredPermissions: []string{%s},\n", strings.Join(quoted, ", "))
			}
		}
		if len(t.Params) > 0 {
			b.WriteString("\t\tParams: []EndpointToolParam{\n")
			for _, p := range t.Params {
				loc := "EndpointToolParam" + strings.ToUpper(p.In[:1]) + p.In[1:]
				if p.Array {
					fmt.Fprintf(&b, "\t\t\t{Name: %q, In: %s, Array: true},\n", p.Name, loc)
				} else {
					fmt.Fprintf(&b, "\t\t\t{Name: %q, In: %s},\n", p.Name, loc)
				}
			}
			b.WriteString("\t\t},\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")

	// gofmt re-aligns each literal's columns to its widest field, so a fresh generation matches the committed file.
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("gofmt generated catalog: %w", err)
	}
	return os.WriteFile(agentToolsGoPath, formatted, 0o644)
}
